import pandas as pd
import numpy as np

# Create df_products (Product Information)
np.random.seed(42)
products = [
    {'product_id': i, 'product_name': f'Product_{i}', 'category': np.random.choice(['Electronics', 'Books', 'Clothing', 'Home Goods'])}
    for i in range(1, 101) # 100 products
]
df_products = pd.DataFrame(products)

print("df_products (first 5 rows):")
display(df_products.head())

# Create df_sales (Sales Information)
np.random.seed(0)
sales = []
for _ in range(100): # 100 sales records
    product_id = np.random.randint(1, 101) # Randomly select product_id from 1 to 100
    quantity = np.random.randint(1, 10)
    price = np.round(np.random.uniform(5.0, 100.0), 2)
    sales.append({'sale_id': len(sales) + 1, 'product_id': product_id, 'quantity': quantity, 'price': price})
df_sales = pd.DataFrame(sales)

print("df_sales (first 5 rows):")
display(df_sales.head())

